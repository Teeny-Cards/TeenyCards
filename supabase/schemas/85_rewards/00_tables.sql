-- Registry of countable things a reward can be earned against. The key is the
-- stable identifier a source reports progress under ('study.cards_reviewed');
-- a future source adds rows here without touching the counting machine.
CREATE TABLE public.reward_metrics (
    key text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);


ALTER TABLE public.reward_metrics OWNER TO postgres;


-- Lifetime tally per (member, metric), stored as a counter that only ever goes
-- up via record_progress — never re-derived from source rows, so a deck reset
-- that deletes reviews cannot unwind milestones already crossed →[K:reward-tally-survives-reset].
CREATE TABLE public.member_tallies (
    member_id uuid NOT NULL,
    metric text NOT NULL,
    tally bigint DEFAULT 0 NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL
);


ALTER TABLE public.member_tallies OWNER TO postgres;


-- Catalogue of earnable milestones. `rewards` is the reward-list payload
-- apply_reward walks; `name_key` is an i18n key, never an English title, so the
-- catalogue carries no copy. Retunable data, not code.
CREATE TABLE public.reward_milestones (
    id bigint NOT NULL,
    metric text NOT NULL,
    threshold bigint NOT NULL,
    rewards jsonb NOT NULL,
    is_active boolean DEFAULT true NOT NULL,
    name_key text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);


ALTER TABLE public.reward_milestones OWNER TO postgres;


ALTER TABLE public.reward_milestones ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.reward_milestones_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);


-- The earned record — one row the first time a member crosses a milestone.
-- `seen_at` is null until the later reveal work marks it shown.
CREATE TABLE public.member_rewards (
    id bigint NOT NULL,
    member_id uuid NOT NULL,
    reward_milestone_id bigint NOT NULL,
    earned_at timestamp with time zone DEFAULT now() NOT NULL,
    seen_at timestamp with time zone
);


ALTER TABLE public.member_rewards OWNER TO postgres;


ALTER TABLE public.member_rewards ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.member_rewards_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
