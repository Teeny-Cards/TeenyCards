-- Append-only paperclip movements. Balance is the SUM of entries
-- (paperclip_balance view), never a stored column — a member can edit
-- their own row, so a stored balance would be spoofable. apply_reward is the
-- sole writer. `member_reward_id` is the earning event that produced the
-- entry, for provenance.
CREATE TABLE public.paperclip_ledger (
    id bigint NOT NULL,
    member_id uuid NOT NULL,
    amount bigint NOT NULL,
    member_reward_id bigint,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);


ALTER TABLE public.paperclip_ledger OWNER TO postgres;


ALTER TABLE public.paperclip_ledger ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.paperclip_ledger_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);


